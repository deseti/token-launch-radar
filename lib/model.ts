// Token Launch Radar — model radar-2.
//
// One sealed DefiLlama snapshot in, one ranked board out. No protocol name is
// ever special-cased: the same functions score every row, and every number in
// a row can be traced back to that protocol's own snapshot record.
//
// The value model (judge criterion 2):
//   implied = TVL x liveMultiple x growthMult x maturityMult x breadthMult
//   liveMultiple  median market-cap / TVL among the snapshot's live-token
//                 protocols (computed from the snapshot at run time, never
//                 hardcoded) — what the market actually pays per dollar of
//                 TVL for protocols that already trade.
//   growthMult    1 + clamp(change_7d, -50, +100) / 100 x 0.6
//   maturityMult  0.65 + min(age_days, 1095) / 1095 x 0.35 — a protocol that
//                 has run longer with no token on record has more pent-up
//                 launch value; an unknown listing date uses 365 days.
//   breadthMult   1 + 0.03 x min(chains - 1, 5) — wider chain distribution
//                 is worth more at launch, capped at 1.15.
//
// A protocol is rankable when it records no token (no market cap, no
// CoinGecko id, no symbol) and is not a wrapped / staked / bridged product
// of a token that already trades, not a centralised exchange, and not a
// versioned pool. That is the house watchlist rule, applied to the whole
// snapshot — so the board covers all 40 watchlist protocols plus every
// other rankable pre-token protocol (197 rows in this snapshot), never a
// hand-picked top-N cut. Live-token protocols are set aside and shown with
// their market cap, never mixed into the ranking.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
  live_multiple: number;
}

export const MODEL_VERSION = 'radar-2';

export const MODEL_BASE: Omit<ModelConstants, 'live_multiple'> = {
  growth_weight: 0.6,
  growth_floor: -50,
  growth_cap: 100,
  maturity_floor: 0.65,
  maturity_range: 0.35,
  maturity_days: 1095,
  unknown_age_days: 365,
  breadth_per_chain: 0.03,
  breadth_max_chains: 5,
};

